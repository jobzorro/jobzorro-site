const TITLE = ["겸업이 들켰다", "겸업 징계", "겸업으로 해고"];
// 경고·징계 한 줄은 선택 결과 뒤에 붙는다(어떻게 수습하든 벌은 같다). 해고는 본문에 붙는다
const TAIL = ["인사 기록에는 구두 경고 한 줄이 남았다.", "한 번 경고를 받은 뒤라 인사위원회가 열렸다. 감봉 6개월.", "세 번째다. 출입증이 더는 찍히지 않는다."];
const tail = (x, st) => `${x || ""} ${TAIL[st - 1]}`.trim();

// stage: 1 경고 · 2 징계 · 3 해고(core.js 의 co.warns). job 을 주면 그 투잡 경위만(시험용)
export function caughtScene(s, r, stage, job, id) {
  const jobs = job ? [job] : caughtJobs(s); if (!jobs.length) return null;
  const co = s.co; if (!co.cgSeen) co.cgSeen = {}; // 옛 저장에는 없는 칸
  const k = jobs.length > 1 ? r.pick(jobs) : jobs[0]; if (!HOW[k]) return null;
  const H = HOW[k];
  let L = H.L.filter((e) => co.cgSeen[e.id] === undefined); if (!L.length) L = H.L; // 다 봤으면 처음부터
  const e = (id && H.L.find((x) => x.id === id)) || r.pick(L);
  co.cgSeen[e.id] = s.t;
  const st = Math.max(1, Math.min(3, stage || 1));
  const choices = st === 3 ? [{ t: "짐을 싼다", eff: {}, text: "오늘부로 투잡이 본업이 됐다. 원하든 원하지 않든." }]
    : e.c.map((c) => (c.check ? { t: c.t, check: c.check, ok: { ...c.ok, text: tail(c.ok.text, st) }, ng: { ...c.ng, text: tail(c.ng.text, st) } } : { t: c.t, eff: c.eff, text: tail(c.text, st) }));
  return { kind: "event", id: "cg_" + e.id, once: "big", tag: "겸업 · " + H.tag, title: `${TITLE[st - 1]} · ${e.t}`, text: st === 3 ? `${e.x} ${TAIL[2]}` : e.x, choices };
}
